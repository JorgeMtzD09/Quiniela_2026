// Mapa invertido: variante normalizada -> token canónico
const ALIAS_LOOKUP = (() => {
  const map = {};
  for (const [canon, variants] of Object.entries(TEAM_ALIASES)) {
    map[canon] = canon;
    for (const v of variants) map[normalizeRaw(v)] = canon;
  }
  return map;
})();

function normalizeRaw(str) {
  return String(str || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u{1F1E6}-\u{1F1FF}]/gu, '')
    .replace(/[^\w\s]/g, ' ')
    .toLowerCase()
    .trim()
    .replace(/\s+/g, ' ');
}

/** Normaliza un nombre de equipo a su token canónico (resuelve es/en y abreviaturas). */
export function normTeam(str) {
  const base = normalizeRaw(str);
  if (!base) return '';
  if (ALIAS_LOOKUP[base]) return ALIAS_LOOKUP[base];
  const words = base.split(' ');
  for (const w of words) {
    if (w.length > 2 && ALIAS_LOOKUP[w]) return ALIAS_LOOKUP[w];
  }
  return base;
}

export function teamsMatch(a, b) {
  const na = normTeam(a);
  const nb = normTeam(b);
  if (!na || !nb) return false;
  return na === nb;
}

/** Convierte fecha+hora ET (EDT) a Date absoluto */
export function etToDate(dateStr, timeET) {
  const [hh, mm] = timeET.split(':').map(Number);
  const iso = `${dateStr}T${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}:00-04:00`;
  return new Date(iso);
}

export function fixtureMatchesPartido(fixture, partido) {
  const homeOk = teamsMatch(fixture.local, partido.local) && teamsMatch(fixture.visitante, partido.visitante);
  const swapOk = teamsMatch(fixture.local, partido.visitante) && teamsMatch(fixture.visitante, partido.local);
  return homeOk || swapOk;
}

/** Busca en el calendario oficial el partido con los mismos dos equipos (sin importar el orden/id). */
export function findFixtureForPartido(partido) {
  return FIXTURES.find(fx => fixtureMatchesPartido(fx, partido)) || null;
}

export function formatDateCDMX(date) {
  return date.toLocaleString('es-MX', {
    weekday: 'short',
    day: '2-digit',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: 'America/Mexico_City',
  });
}

/** Clave de día (YYYY-MM-DD) en hora del centro de México, para agrupar partidos. */
export function dayKeyCDMX(date) {
  return date.toLocaleDateString('en-CA', { timeZone: 'America/Mexico_City' });
}

/** Encabezado de día: "Sábado 13 de junio" (hora del centro de México). */
export function formatDayHeaderCDMX(date) {
  const s = date.toLocaleDateString('es-MX', {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    timeZone: 'America/Mexico_City',
  });
  return s.charAt(0).toUpperCase() + s.slice(1);
}
